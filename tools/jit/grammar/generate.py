"""Export the shared Lark grammar as C++ tables for the standalone runner."""

from __future__ import annotations

import argparse
import base64
import json
import re
import textwrap
import zlib
from pathlib import Path

from lark import Token, Tree

from clang_toolkit.cli.callable_help import builtin_callable_help
from clang_toolkit.cli.help import COMMAND_HELP, MATCHER_HELP
from clang_toolkit.cli.matcher_catalog import MATCHER_METADATA
from clang_toolkit.cli.runtime.prototype.help import render_help, render_help_markdown
from clang_toolkit.cli.runtime.prototype.repl_editor import _KEYWORDS, _keyword_patterns
from clang_toolkit.cli.jit_syntax import parser


def literal(text: str) -> str:
    # Raw literals preserve the regex escapes and literal whitespace from Lark.
    delimiter = "ctk_grammar"
    if f'){delimiter}"' in text:
        raise ValueError("the grammar contains the generated C++ raw string delimiter")
    return f'R"{delimiter}({text}){delimiter}"'


def generate() -> str:
    grammar = parser()
    terminals = grammar.terminals
    nonterminals = list(dict.fromkeys(rule.origin.name for rule in grammar.rules))
    names = [terminal.name for terminal in terminals] + nonterminals
    symbol = {name: number for number, name in enumerate(names)}

    rhs: list[str] = []
    rules: list[str] = []
    for rule in grammar.rules:
        origin = rule.origin.name
        inline = rule.options.expand1 and rule.alias is None
        rules.append(
            f"  {{{symbol[origin]}, {json.dumps(rule.alias or origin)}, "
            f"{len(rhs)}, {len(rule.expansion)}, {rule.order}, "
            f"{rule.options.priority or 0}, {str(inline).lower()}}},"
        )
        for item in rule.expansion:
            discard = item.is_term and item.filter_out and not rule.options.keep_all_tokens
            splice = not item.is_term and item.name.startswith("_")
            mode = "Discard" if discard else "Splice" if splice else "Keep"
            rhs.append(f"{{{symbol[item.name]}, ChildMode::{mode}}}")

    lines = [
        "// Generated by tools/jit/grammar/generate.py from the shared CTK grammar.",
        "constexpr Terminal terminals[] = {",
        *(
            f"  {{{json.dumps(terminal.name)}, {literal(terminal.pattern.to_regexp())}, "
            f"{terminal.priority}}},"
            for terminal in terminals
        ),
        "};",
        f"constexpr unsigned symbol_count = {len(names)};",
        f"constexpr Symbol start_symbol = {symbol[grammar.options.start[0]]};",
        "constexpr Symbol ignores[] = {"
        + ", ".join(str(symbol[name]) for name in grammar.ignore_tokens)
        + "};",
        "constexpr Rhs expansions[] = {",
        *("  " + ", ".join(rhs[i : i + 6]) + "," for i in range(0, len(rhs), 6)),
        "};",
        "constexpr Rule rules[] = {",
        *rules,
        "};",
    ]
    # CR characters occur in lexer literals and must survive C++ translation
    # phases, which normalize physical line endings.
    return "\n".join(lines).replace("\r", '\\r') + "\n"


def generate_help() -> str:
    topics = sorted(
        set(COMMAND_HELP)
        | set(MATCHER_HELP)
        | set(builtin_callable_help())
        | {"", "loops", "foreach", "while", "repeat", "break", "continue",
           "predicates", "runnables", "functions"}
    )
    documents = {}
    for topic in topics:
        tree = Tree("help_shortcut", [Token("HELP_SHORT_TOPIC", topic)])
        documents[topic] = [render_help(tree), render_help_markdown(tree)]
    data = json.dumps(documents, ensure_ascii=False, separators=(",", ":")).encode()
    encoded = base64.b64encode(zlib.compress(data, 9)).decode("ascii")
    keywords = set(_KEYWORDS)
    for terminal in parser().terminals:
        word = re.match(r"[A-Za-z_]\w*", terminal.pattern.value)
        if word and any(pattern.fullmatch(word[0]) for pattern in _keyword_patterns()):
            keywords.add(word[0])
    vocabulary = {"editor_keywords": keywords}
    for name, metadata in MATCHER_METADATA.items():
        vocabulary.setdefault(f"editor_{metadata[0]}_matchers", set()).add(name)
    roles = "".join(
        f"constexpr char {role}[] =\n"
        + "\n".join(f'    "{line} "' for line in textwrap.wrap(" ".join(sorted(words)), 95))
        + ";\n"
        for role, words in sorted(vocabulary.items())
    )
    return (
        "// Generated by tools/jit/grammar/generate.py.\n"
        f"constexpr std::size_t help_size = {len(data)};\n"
        "constexpr char help_data[] =\n"
        + "\n".join(f'    "{line}"' for line in textwrap.wrap(encoded, 100))
        + ";\n"
        + roles
    )


def main() -> None:
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--check", action="store_true")
    options = cli.parse_args()
    for name, content in (("tables.inc", generate()), ("help.inc", generate_help())):
        output = Path(__file__).with_name(name)
        expected = content.encode()
        if options.check:
            if not output.is_file() or output.read_bytes() != expected:
                cli.exit(1, f"Generated CTK {name} is stale\n")
        else:
            output.write_bytes(expected)


if __name__ == "__main__":
    main()
